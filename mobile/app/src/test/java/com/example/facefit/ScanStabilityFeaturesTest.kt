package com.example.facefit

import com.example.facefit.facefit.analysis.FaceAnalyzer
import com.example.facefit.facefit.analysis.ScanStabilityFeatures
import org.junit.Assert.*
import org.junit.Test

class ScanStabilityFeaturesTest {
    @Test fun realLandmarksFromFiveFacesMatchPythonV10() {
        val lines = javaClass.getResourceAsStream("/exp18b_geometry_reference.csv")!!
            .bufferedReader().use { it.readLines() }
        val header = lines.first().split(',')
        assertEquals(6, lines.size)
        for (line in lines.drop(1)) {
            val row = header.zip(line.split(',')).toMap()
            val landmarks = List(478) { i ->
                FaceAnalyzer.LandmarkPoint(row["p${i}_x"]?.toFloat() ?: .5f,
                    row["p${i}_y"]?.toFloat() ?: .5f)
            }
            val features = ScanStabilityFeatures.extract(landmarks,
                row.getValue("width").toInt(), row.getValue("height").toInt())!!
            ScanStabilityFeatures.names.forEachIndexed { i, name ->
                assertEquals(name, row.getValue(name).toFloat(), features[i], .000002f)
            }
        }
    }

    private fun points() = List(478) { i ->
        FaceAnalyzer.LandmarkPoint((0.2 + i % 23 * 0.02).toFloat(),
            (0.15 + i / 23 * 0.025).toFloat())
    }

    @Test fun allSevenFeaturesMatchOriginalV10PythonExtractor() {
        // Generated by compute_features in the actual 18B source on this float32 grid.
        val expected = listOf(1.7812499511055655, 0.9388323700020564, 0.9702609002187648,
            0.6473029779481931, 4.136144092417838, 0.703125017462298, 0.800000044703483)
        val actual = ScanStabilityFeatures.extract(points(), 640, 960)!!
        assertEquals(7, actual.size)
        expected.forEachIndexed { i, value -> assertEquals(value.toFloat(), actual[i], 0.000002f) }
    }

    @Test fun mirroringPreservesChinDepthAndAllSevenMeasurements() {
        val original = points()
        val expected = ScanStabilityFeatures.extract(original, 640, 960)!!
        for (mirrored in listOf(original.map { it.copy(x = 1f - it.x) },
                original.map { it.copy(y = 1f - it.y) })) {
            val actual = ScanStabilityFeatures.extract(mirrored, 640, 960)!!
            expected.indices.forEach { i -> assertEquals(expected[i], actual[i], .00001f) }
        }
    }

    @Test fun changingImageEncodingAspectAndUniformScalePreservesPhysicalFeatures() {
        val original = points()
        val expected = ScanStabilityFeatures.extract(original, 640, 960)!!
        val landscape = original.map { it.copy(x = it.x * 640f / 960f, y = it.y * 960f / 640f) }
        val actual = ScanStabilityFeatures.extract(landscape, 960, 640)!!
        val scaled = ScanStabilityFeatures.extract(original, 1280, 1920)!!
        expected.indices.forEach { i ->
            assertEquals(expected[i], actual[i], 0.00001f)
            assertEquals(expected[i], scaled[i], 0.00001f)
        }
    }

    @Test fun missingCollapsedAndNonFiniteLandmarksAreRejected() {
        assertNull(ScanStabilityFeatures.extract(emptyList(), 640, 960))
        assertNull(ScanStabilityFeatures.extract(points(), 0, 960))
        assertNull(ScanStabilityFeatures.extract(List(478) { FaceAnalyzer.LandmarkPoint(0.5f, 0.5f) }, 640, 960))
        val invalid = points().toMutableList().apply { this[150] = this[150].copy(x = Float.NaN) }
        assertNull(ScanStabilityFeatures.extract(invalid, 640, 960))
        assertFalse(ScanStabilityFeatures.isValid(List(7) { Float.POSITIVE_INFINITY }))
        assertFalse(ScanStabilityFeatures.isValid(List(10) { 1f }))
        assertFalse(ScanStabilityFeatures.isValid(List(7) { -1f }))
    }
}
